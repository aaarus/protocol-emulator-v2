// CRC-7 polynomial x^7+x^3+1 over bits 11010010 produces 0x2E.
CONFIG_GPIO 0, OUTPUT, PUSH_PULL, IMMEDIATE
WRITE_REG 0x00, 0x09
WRITE_REG 0x0C, 7
WRITE_REG 0x0D, 0
WRITE_REG 0x0E, 1
CRC ENABLE
LOAD_TX TX0, 0x4B
LOOP 8
    SHIFT_OUT TX0
LOOP_END
CRC DISABLE
LOOP 7
    SHIFT_OUT CRC_TX
LOOP_END
STOP
